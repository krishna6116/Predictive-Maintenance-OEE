"""Write docs/MAINTENANCE_OEE.md from the saved Phase 6 results, so it can never drift from them.

Run:  python -m maintenance.report_phase6       (after python -m maintenance.run_phase6)
`python -m maintenance.verify_phase6` checks that the committed document equals a fresh rendering.
"""
import json
import sys
from pathlib import Path

import pandas as pd

from maintenance import config as C

DOC = Path("docs/MAINTENANCE_OEE.md")
CSV = {"float_precision": "round_trip"}
POLICIES = ("Run to failure", "Fixed interval", "Predictive")
TRACE_SENSORS = ("s4", "s11")


def pct(x):
    return f"{x:.1%}"


def trace_engines(snap, mach, ds):
    """Fixed rule, not hand-picked: the most urgent engine at the snapshot, the flagged engine closest to the
    threshold, and the lowest-numbered engine that failed under the predictive policy (if any)."""
    s = snap[snap.dataset == ds]
    picks = [int(s.loc[s.rul_low.idxmin(), "engine_id"])]
    f = s[s.flagged]
    if len(f):
        picks.append(int(f.loc[f.rul_low.idxmax(), "engine_id"]))
    pf = mach[(mach.dataset == ds) & (mach.policy == "Predictive") & (mach.event == "failure")]
    if len(pf):
        picks.append(int(pf.machine.min()))
    return list(dict.fromkeys(picks))


def trace_rows(ds, e, snap, wo, mach):
    from maintenance.simulate import oee
    from pipeline.check_raw_data import load
    from pipeline.config import RAW
    sc = json.loads(Path("features/scaler.json" if ds == "FD001" else f"features/scaler_{ds}.json").read_text())
    s = snap[(snap.dataset == ds) & (snap.engine_id == e)].iloc[0]
    raw = load(RAW / f"test_{ds}.txt")
    last = raw[(raw.unit == e)].sort_values("cycle").iloc[-1]
    w = wo[(wo.dataset == ds) & (wo.engine_id == e)]
    m = mach[(mach.dataset == ds) & (mach.machine == e) & (mach.policy == "Predictive")].iloc[0]
    o = oee(mach[(mach.dataset == ds) & (mach.machine == e) & (mach.policy == "Predictive")])
    sens = ", ".join(f"{c} {last[c]:.2f} -> {(last[c] - sc[c]['mean']) / sc[c]['std']:+.3f}" for c in TRACE_SENSORS)
    order = ("none (lower bound never reached the threshold before the failure)" if w.empty else
             f"created after cycle {int(w.created_cycle.iloc[0])} using the forecast from cycle {int(w.forecast_cycle.iloc[0])} "
             f"(aged {int(w.forecast_age.iloc[0])} cycles), lower bound {w.rul_low.iloc[0]:.1f}, {w.risk.iloc[0]}; service "
             f"booked for cycle {int(w.service_cycle.iloc[0])}; {w.status.iloc[0]}")
    snap_plan = (f"day {int(s.service_day)} (after {int(s.service_after_cycles)} more cycles)" if not pd.isna(s.service_day)
                 else ("flagged, no crew free in the 7 days" if s.flagged else "not flagged"))
    return [
        (f"{ds} engine {e}", ""),
        ("1. Raw input (last observed cycle)", f"cycle {int(s.cycle)}; {', '.join(f'{c} {last[c]:.2f}' for c in TRACE_SENSORS)} (of 14 sensors)"),
        ("2. Model input (scaled, training-engine scaler)", sens + "; window = last 40 cycles"),
        ("3. Point forecast (published LSTM, dropout off)", f"{s.rul_point:.2f} cycles"),
        ("4. MC dropout (100 passes) and rule-E interval", f"mean {s.rul_mc_mean:.2f}, sd {s.rul_mc_std:.2f}, k {s.k:.3f} -> "
                                                          f"90% interval {s.rul_low:.2f} to {s.rul_high:.2f}"),
        ("5. Value used by the decision", f"lower bound {s.rul_low:.2f} (rule: flag if <= {C.ALERT_THRESHOLD})"),
        ("6. Snapshot alert", (f"{s.risk}: {s.reason}" if s.flagged else "not flagged")),
        ("7. Snapshot schedule (CP-SAT)", snap_plan + f"; true remaining life {s.true_rul:.0f} -> {s.outcome}"),
        ("8. Replay work order (predictive policy)", order),
        ("9. Simulated outcome", f"{m.event} after {int(m.run_cycles)} of {int(m.life)} cycles (true failure point); "
                                 f"wasted {int(m.wasted_cycles)}, degraded {int(m.degraded_cycles)} cycles; downtime {m.downtime_hours:.0f} h"),
        ("10. OEE for this machine (simulated)", f"A {pct(o['availability'])} x P {pct(o['performance'])} x Q {pct(o['quality'])} "
                                                 f"= {pct(o['oee'])}"),
    ]


def render() -> str:
    r = json.loads(Path("maintenance/results_phase6.json").read_text())
    snap = pd.read_csv("maintenance/snapshot_decisions_phase6.csv", **CSV)
    wo = pd.read_csv("maintenance/work_orders_phase6.csv", **CSV)
    mach = pd.read_csv("maintenance/machines_phase6.csv", **CSV)
    p = r["plant"]
    out = ["# Maintenance decisions and OEE (Phase 6)", "",
           "Generated by `python -m maintenance.report_phase6` from `maintenance/results_phase6.json`; do not edit by hand. "
           "Independent checks: `python -m maintenance.verify_phase6`. Walkthrough: `notebooks/06_maintenance.ipynb`.", "",
           "> **Simulation, not measured results.** NASA C-MAPSS is simulated engine data with no production records. "
           "The plant, its output, downtime and OEE below are a documented simulation. The forecasts are real model outputs; "
           "everything after them is simulated.", "",
           f"**Run ID:** `{r['run_id']}` (a hash of the inputs and settings; the same inputs give the same ID, so database "
           f"writes replace rather than duplicate). **Environment:** OR-Tools {r['environment']['ortools']}, "
           f"{r['environment']['solver_workers']} solver worker, seed {r['environment']['solver_seed']}.", "",
           "## Pipeline", "",
           "Forecast (published LSTM + rule-E 90% interval) -> alert on the lower bound -> CP-SAT schedule under crew "
           "limits -> simulated plant -> OEE. Forecasts come from the published seed-0 LSTM of each dataset "
           f"({', '.join(d['model_id'] for d in r['datasets'].values())}). Forecasts at every observed test cycle were "
           "produced by rebuilding that model (`python -m maintenance.forecasts`), which first reproduces the published "
           "last-cycle predictions and all MC passes exactly.", "",
           "## Settings and assumptions", "",
           "| Setting | Value | Source |", "| --- | --- | --- |",
           f"| Alert | lower 90% bound <= {r['settings']['alert_threshold']} cycles; critical <= 5, high <= 10, medium <= 20 | guide |",
           f"| Schedule | {r['settings']['horizon_days']} days, {r['settings']['crews_per_day']} crews a day, "
           f"{r['settings']['cycles_per_day']} cycles a day | guide |",
           f"| Schedule cost | {r['settings']['weights']['late']} per late cycle, {r['settings']['weights']['early']} per early "
           f"cycle, {r['settings']['weights']['unserved']} per unserved engine | guide |",
           f"| Plant | {p['hours_per_cycle']:g} h per cycle, {p['units_per_hour']:g} units/h, service {p['service_hours']:g} h, "
           f"failure {p['failure_hours']:g} h | guide |",
           f"| Degradation | last {p['degraded_cycles']} cycles: speed -{p['degraded_speed_loss']:.0%}, scrap "
           f"{p['degraded_scrap']:.0%} (otherwise {p['normal_scrap']:.0%}) | guide |",
           f"| Fixed interval | N = 10th percentile of training lifetimes: FD001 {r['datasets']['FD001']['fixed_interval_n']}, "
           f"FD003 {r['datasets']['FD003']['fixed_interval_n']} cycles | guide, data |"]
    for k, v in r["assumptions"].items():
        out.append(f"| {k.replace('_', ' ').capitalize()} | {v} | assumption (guide silent) |")
    out += ["", "## A. Decision snapshot (each test engine's last observed cycle)", "",
            "The guide's alert and schedule applied once at the official evaluation point, then scored against NASA's true "
            "remaining life. A service on day d happens after 2d more cycles; it is in time if that is before the failure point. "
            "This is a separate view from the policy replay in B, where forecasts arrive every day, so an engine may already "
            "be serviced there before its last NASA reading.", "",
            "| Dataset | Flagged (critical / high / medium) | Scheduled | Solver | Outcomes | Mean life left at service |",
            "| --- | --- | --- | --- | --- | --- |"]
    for ds, d in r["datasets"].items():
        s = d["snapshot"]
        rc = s["risk_counts"]
        outs = "; ".join(f"{k} {v}" for k, v in sorted(s["outcomes"].items()))
        out.append(f"| {ds} | {s['flagged']} ({rc.get('critical', 0)} / {rc.get('high', 0)} / {rc.get('medium', 0)}) | "
                   f"{s['scheduled']} of {s['flagged']} (per day {list(s['per_day'].values())}) | {s['schedule_status']}, cost "
                   f"{s['objective']} | {outs} | {s['wasted_cycles_mean']:.1f} cycles |")
    out += ["", "Schedule-weight sensitivity at the snapshot (guide: test how the plan changes). Late and early cycles are "
                "measured against each engine's lower bound:", "",
            "| Dataset | Weights | Engines served | Same engines as guide weights | Late cycles | Early cycles | Unserved |",
            "| --- | --- | --- | --- | --- | --- | --- |"]
    for ds, d in r["datasets"].items():
        for k, v in d["snapshot"]["weight_sensitivity"].items():
            out.append(f"| {ds} | {k} | {len(v['served'])} | {'yes' if v['same_engines_served'] else 'no'} | "
                       f"{v['late_cycles']} | {v['early_cycles']} | {v['unserved']} |")
    worse = [(ds, k, v) for ds, d in r["datasets"].items() for k, v in d["snapshot"]["weight_sensitivity"].items()
             if v["unserved"] > d["snapshot"]["weight_sensitivity"]["guide (100 late / 1 early)"]["unserved"]]
    if worse:
        out += ["", "Finding: " + "; ".join(f"with {k} on {ds}, {v['unserved']} engines are left unserved" for ds, k, v in worse)
                + f". Once servicing an engine late costs more than the unserved penalty ({r['settings']['weights']['unserved']}), "
                  "the solver prefers not to service it at all. The cost only means \"service every engine you can\" while "
                  "the unserved penalty stays above the worst late cost."]
    late = [(ds, d["snapshot"]["weight_sensitivity"]["guide (100 late / 1 early)"]["late_cycles"]) for ds, d in r["datasets"].items()]
    if any(l for _, l in late):
        out += ["", "Late cycles with the guide's weights (" + ", ".join(f"{ds} {l}" for ds, l in late) + ") come from engines "
                "whose lower bound is already at or near 0: with three crews a day not all of them can be serviced today."]
    out += ["", "## B. Policy comparison (Simulation, not measured results)", "",
            "| Dataset | Policy | Unplanned failures | Planned services | Downtime (hours) | Wasted life (cycles) | Availability | Performance | Quality | OEE |",
            "| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |"]
    rows = [(ds, d["policies"]) for ds, d in r["datasets"].items()] + [("Pooled (200)", r["pooled"])]
    for ds, pol in rows:
        for name in POLICIES:
            s = pol[name]
            out.append(f"| {ds} | {name} | {s['unplanned_failures']} | {s['planned_services']} | {s['downtime_hours']:,.0f} | "
                       f"{s['wasted_cycles']:,} | {pct(s['availability'])} | {pct(s['performance'])} | {pct(s['quality'])} | "
                       f"**{pct(s['oee'])}** |")
    out += ["", "OEE gaps, paired bootstrap over machines (2,000 resamples; approximate, because machines share crews "
                "under the predictive policy):", "", "| Comparison | FD001 | FD003 | Pooled |", "| --- | --- | --- | --- |"]
    for k in ("Predictive - Run to failure", "Predictive - Fixed interval"):
        cell = lambda g: f"{g['diff'] * 100:+.2f} points ({g['ci'][0] * 100:+.2f} to {g['ci'][1] * 100:+.2f})"
        out.append(f"| {k} | {cell(r['datasets']['FD001']['oee_gaps'][k])} | {cell(r['datasets']['FD003']['oee_gaps'][k])} | "
                   f"{cell(r['pooled_gaps'][k])} |")
    pf = mach[(mach.policy == "Predictive") & (mach.event == "failure")]
    lastc = snap.set_index(["dataset", "engine_id"]).cycle
    after = sum(1 for ds, e, L in zip(pf.dataset, pf.machine, pf.life) if L > lastc[(ds, e)])
    lowmiss = sum(1 for ds, e in zip(pf.dataset, pf.machine)
                  if (lambda s: s.rul_low > s.true_rul)(snap[(snap.dataset == ds) & (snap.engine_id == e)].iloc[0]))
    out += ["", f"**Why the predictive policy still has {len(pf)} failures:** all {after} happen after the machine's NASA test "
                f"data has ended, so the planner was working from its last forecast, aged cycle by cycle. In {lowmiss} of them the "
                "lower bound at the last reading was already above the true remaining life (an interval miss, which a 90% "
                "interval allows about one time in ten). With live data, new readings would keep correcting the forecast; here "
                "they cannot, so this is a limitation of the truncated test files, not something fixed by tuning.", "",
            "Predictive replay: " + "; ".join(
                f"{ds} {d['predictive_replay']['days']} days, {d['predictive_replay']['solves']} CP-SAT solves (all "
                f"{'OPTIMAL' if d['predictive_replay']['all_optimal'] else 'not all optimal'}), {d['predictive_replay']['work_orders']} "
                f"work orders ({', '.join(f'{k} {v}' for k, v in d['predictive_replay']['order_status'].items())}), at most "
                f"{d['predictive_replay']['max_unserved_in_a_day']} flagged engines left unserved in a day"
                for ds, d in r["datasets"].items()) + ".", "",
            "## Sensitivity (how the comparison moves when assumptions change; nothing was chosen from this)", "",
            "| Change | Dataset | Run to failure | Fixed interval | Predictive | Predictive failures |", "| --- | --- | --- | --- | --- | --- |"]
    for ds, d in r["datasets"].items():
        base = d["policies"]
        out.append(f"| guide settings | {ds} | {pct(base['Run to failure']['oee'])} | {pct(base['Fixed interval']['oee'])} | "
                   f"{pct(base['Predictive']['oee'])} | {base['Predictive']['unplanned_failures']} |")
        for k, v in d["sensitivity"].items():
            out.append(f"| {k} | {ds} | {pct(v['Run to failure']['oee'])} | {pct(v['Fixed interval']['oee'])} | "
                       f"{pct(v['Predictive']['oee'])} | {v['Predictive']['unplanned_failures']} |")
    mf = {ds: d["predictive_replay"]["max_flagged_in_a_day"] for ds, d in r["datasets"].items()}
    out += ["", "Crew count barely matters in the replay: new alerts are spread over months, and at most "
                + ", ".join(f"{v} ({ds})" for ds, v in mf.items()) + " engines were newly flagged on any one day, against "
                f"{r['settings']['crews_per_day']} crews. The crew limit binds at the snapshot instead, where many engines are "
                "flagged at once. A higher alert threshold gives earlier, safer services in this simulation; it is reported "
                "here only, not adopted, because choosing it from these results would tune the policy on the test engines."]
    out += ["", "## Forecast-to-OEE traces", "",
            "Engines chosen by a fixed rule: the most urgent at the snapshot, the flagged engine closest to the threshold, "
            "and the lowest-numbered engine that failed under the predictive policy.", ""]
    for ds in r["datasets"]:
        for e in trace_engines(snap, mach, ds):
            rows_ = trace_rows(ds, e, snap, wo, mach)
            out += [f"**{rows_[0][0]}**", "", "| Stage | Value |", "| --- | --- |"]
            out += [f"| {a} | {b} |" for a, b in rows_[1:]] + [""]
    out += ["## Limitations", "",
            "- The plant, production, downtime and OEE are simulated with the guide's assumptions; no real plant data is used.",
            "- NASA test files stop before failure, so the predictive policy has no new readings late in each machine's life.",
            "- One life per machine (renewal accounting); spare parts, travel time and crew skills are not modelled.",
            "- Fixed-interval and run-to-failure services are not crew-limited, which favours them.",
            "- Bootstrap intervals treat machine outcomes as independent although the predictive policy's machines share crews.", ""]
    return "\n".join(out)


def main() -> int:
    DOC.write_text(render(), encoding="utf-8")
    print(f"Wrote {DOC}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
