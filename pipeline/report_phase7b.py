"""Write docs/MONITORING_7B.md from the saved Phase 7b results, so it can never drift from them.

Run:  python -m pipeline.report_phase7b        (after the replays, check_phase7b, fault_suite)
`python -m pipeline.verify_phase7b` checks that the committed document equals a fresh rendering.
"""
import json
import sys
from pathlib import Path

import pandas as pd

OUT = Path("results/phase7b")
DOC = Path("docs/MONITORING_7B.md")
CRITERIA = json.loads(Path("pipeline/phase7b_criteria.json").read_text())


def pct(x, d=1):
    return f"{x:.{d}%}"


def mark(ok):
    return "pass" if ok else "**FAIL**"


def flag_rate(scenario: str) -> dict:
    h = pd.read_csv(OUT / scenario / "phase7_health.csv")
    return {ds: (int(g.needs_retraining.sum()), len(g)) for ds, g in h.groupby("dataset")}


def render() -> str:
    rule = json.loads(Path("pipeline/monitoring_rule_v2.json").read_text())
    rule21 = json.loads(Path("pipeline/monitoring_rule_v2_1.json").read_text())
    chk = json.loads((OUT / "checks.json").read_text())
    fs = json.loads((OUT / "fault_suite.json").read_text())
    res = {ds: json.loads(Path(f"models/results_{ds}.json").read_text()) for ds in ("FD002", "FD004")}
    d, h = rule["drift"], rule["health"]
    c1 = chk["C1"]
    out = ["# Monitoring, improved and re-tested (Phase 7b)", "",
           "Generated by `python -m pipeline.report_phase7b`; do not edit by hand. Independent checks: "
           "`python -m pipeline.verify_phase7b`. Walkthrough: `notebooks/07b_monitoring.ipynb`. Phase 7: `docs/MONITORING.md`.", "",
           "**Why:** Phase 7's drift test raised false alarms in 11.6% of clean test runs (target 5%), because it compared sensor "
           "readings with training engines of the same age, not the same wear. Phase 7b replaces it and re-tests it on data "
           "nobody had seen: NASA's FD002 and FD004 (six operating conditions; FD004 also has two fault modes).", "",
           "**Order of work (each step committed before the next could influence it):** success criteria; the new rule, chosen "
           "on training and validation engines only; the FD002/FD004 models and settings; then the test replays.", "",
           "## The rule (pre-registered, v2)", "",
           "- **Wear-adjusted residuals:** each reading is compared with what that sensor should read for an engine of that age "
           "and predicted remaining life (spline models on training engines with out-of-fold predictions), divided by the "
           "expected spread: z = (reading - expected) / spread.",
           f"- **Drift:** per-engine mean z over the last {d['window_shifts']} shifts vs the training engines' windows, KS, Holm "
           f"over 14 sensors. A sensor triggers retraining if drifted (alpha {d['alpha']:g}) in {d['k']} of the last {d['m']} runs, "
           f"or once with p < {d['alpha_strong']:g} (reason: *sensor fault suspected, check the sensor before retraining*).",
           f"- **Health:** squared error of the last 20 labelled engines vs the error expected for engines of the same life "
           f"(limit {h['error_ratio_limit']}x), and a binomial test of their lower-bound misses against the validation rate "
           f"(alpha {h['miss_alpha']}).",
           f"- **Calibration fleets:** {d['fleets']}. On the same fleets the old Phase 7 test raised up to "
           f"{pct(max(v for x in d['old_phase7_test_false_alarms_on_same_fleets'].values() for v in x.values() if v is not None))} "
           f"false alarms; the new rule at most {pct(max(d['false_alarm_chosen'].values()))} (budget {pct(rule['budgets']['drift'], 0)}).", "",
           "## Fresh fleets (frozen FD001 recipe)", "",
           "| Dataset | Test engines | LSTM test RMSE | Age-only | Fleet average | 90% interval coverage |", "| --- | --- | --- | --- | --- | --- |"]
    for ds, r in res.items():
        b = r["baselines_test_rmse"]
        out.append(f"| {ds} | {r['engines']['test']} | {r['models']['LSTM']['rmse']:.2f} | {b['Age only (quadratic in cycle)']:.2f} | "
                   f"{b['Fleet average']:.2f} | {pct(r['mc_dropout']['test_coverage'], 0)} |")
    out += ["", "## Pre-registered criteria (rule v2, as committed)", "",
            "| Criterion | Dataset | Result | Verdict |", "| --- | --- | --- | --- |"]
    for ds in ("FD002", "FD004"):
        s, g = c1[f"{ds} synchronized"], c1[f"{ds} staggered"]
        ok = s["rate"] <= 0.05 and g["rate"] <= 0.05
        out.append(f"| C1 clean-run retraining flags <= 5% | {ds} | synchronized {s['flagged']}/{s['runs']} = {pct(s['rate'])}; "
                   f"staggered {g['flagged']}/{g['runs']} = {pct(g['rate'])} | {mark(ok)} |")
    for ds in ("FD002", "FD004"):
        c = chk["C2"][ds]
        out.append(f"| C2 one +5% batch on {c['sensor']} sets the flag | {ds} | {c['quarantined']}/{c['readings']} readings quarantined; "
                   f"reason: {c['reasons']}; clean runs before it flagged: {c['clean_runs_flagged']} | {mark(c['passed'])} |")
    for ds in ("FD002", "FD004"):
        st, rp = fs[ds]["step"], fs[ds]["ramp"]
        out.append(f"| C3 +1 sd step flagged within 10 shifts in >= 80% | {ds} | {st['detected']}/{st['testable']} = {pct(st['rate'], 0)}, "
                   f"median delay {st['median_delay']:g} shifts | {mark(st['rate'] >= 0.8)} |")
        out.append(f"| C4 ramp to +2 sd flagged before it ends in >= 80% | {ds} | {rp['detected']}/{rp['testable']} = {pct(rp['rate'], 0)}, "
                   f"median delay {rp['median_delay']:g} shifts | {mark(rp['rate'] >= 0.8)} |")
    out += ["", "Fault suite, reported without pass/fail (fleet-wide fault in one sensor, staggered fleet, 84 injections per type "
                "and dataset; detection = a flag naming that sensor):", "",
            "| Fault | FD002 | FD004 |", "| --- | --- | --- |"]
    for kind, label in (("stuck", "Stuck sensor"), ("noise", "Noise x3"), ("dropout", "10% dropouts")):
        cells = []
        for ds in ("FD002", "FD004"):
            k = fs.get(ds, {}).get(kind)
            cells.append("-" if not k else f"{k['detected']}/{k['testable']} ({pct(k['rate'] or 0, 0)})"
                         + (f", median delay {k['median_delay']:g}" if k["median_delay"] is not None else ""))
        out.append(f"| {label} | {' | '.join(cells)} |")
    eq = fs["mirror_equivalence"]
    out += ["", f"The fault suite mirrors the flow offline (84 injections x 5 faults x 2 datasets would take days in the real flow). "
                f"Checks: re-predicting clean windows gives the clean replay's forecasts exactly (max difference "
                f"{max(fs[ds]['mirror_self_check_max_diff'] for ds in ('FD002', 'FD004')):g}); on an injected {eq['dataset']} run the "
                f"real flow and the mirror gave the same flag in every compared shift and the same p-values (largest gap "
                f"{eq['max_p_gap']:g}). Dropouts are invisible to the drift test by design (missing readings are quarantined as "
                "unreadable); they show up as quarantined rows.", "",
            "## Why FD004 failed C1", ""]
    sp = chk["diagnosis"]["spread"]
    fd4 = chk["diagnosis"]["fd004"]
    v21 = {"synchronized": flag_rate("v21_fresh_synchronized"), "staggered": flag_rate("v21_fresh_staggered")}
    out += ["**A defect, found and fixed, that was not the cause.** The spread model fits the mean absolute residual directly "
            "and can go to zero or below in sparse corners; the code then divides by a floor of 1e-6. On FD004's oldest test "
            "engines this produced standardised residuals in the millions:", "",
            "| Dataset | Readings with abs(z) > 20, v2 | Largest abs(z), v2 | Smallest predicted spread, v2 | Same three, v2.1 (log-scale spread) |",
            "| --- | --- | --- | --- | --- |"]
    for ds, v in sp.items():
        out.append(f"| {ds} | {v['v2']['readings_abs_z_over_20']} | {v['v2']['max_abs_z']:,.0f} | {v['v2']['smallest_predicted_spread']:.2f} | "
                   f"{v['v2.1']['readings_abs_z_over_20']}, {v['v2.1']['max_abs_z']:.1f}, {v['v2.1']['smallest_predicted_spread']:.2f} |")
    out += ["", f"v2.1 models log(abs residual), so the spread is positive by construction; re-chosen with the same validation-only "
                f"procedure it kept every decision parameter (alpha {rule21['drift']['alpha']:g}, {rule21['drift']['k']} of "
                f"{rule21['drift']['m']}, strong {rule21['drift']['alpha_strong']:g}, error limit {rule21['health']['error_ratio_limit']}, "
                f"miss alpha {rule21['health']['miss_alpha']}). It is **post hoc**: every test set had been seen, so none of its test "
                "results is a confirmation. Re-scored with v2.1, FD004 still fails:", "",
            "| Clean-run flags | v2 (pre-registered) | v2.1 (post hoc) |", "| --- | --- | --- |"]
    for ds in ("FD002", "FD004"):
        for fl in ("synchronized", "staggered"):
            a = c1[f"{ds} {fl}"]
            b = v21[fl][ds]
            out.append(f"| {ds} {fl} | {a['flagged']}/{a['runs']} = {pct(a['rate'])} | {b[0]}/{b[1]} = {pct(b[0] / b[1])} |")
    corr = fd4["correlation_with_mode_signature"]
    out += ["", f"**The likely cause: two fault modes.** FD004's flags are persistent drift in several sensors at once, late in the "
                f"replay (shifts {fd4['flagged_shifts_v21_synchronized'][0]}-{fd4['flagged_shifts_v21_synchronized'][1]}, synchronized), "
                "when few engines are left. Their mean residual pattern correlates "
                f"{corr['-1']:+.2f} and {corr['1']:+.2f} with the end-of-life residual signatures of the two groups of FD004 training "
                "engines split by the direction of s20 (a proxy for the two fault modes, which NASA does not label). The expected-level "
                "model averages the two modes, so a late group dominated by one mode's degradation pattern looks drifted. This is "
                "consistent with the data but not proven: the crude mode proxy does not show the survivors dominated by one mode. A "
                "mode-aware expected level is the next step; it would need data nobody has seen yet to confirm it.", "",
            "Post hoc on FD001/FD003 (their test sets were seen in Phases 5-7):", "",
            "| Clean-run flags | v2 | v2.1 |", "| --- | --- | --- |"]
    for fl in ("synchronized", "staggered"):
        a, b = flag_rate(f"posthoc_{fl}"), flag_rate(f"v21_posthoc_{fl}")
        for ds in ("FD001", "FD003"):
            out.append(f"| {ds} {fl} | {a[ds][0]}/{a[ds][1]} = {pct(a[ds][0] / a[ds][1])} | {b[ds][0]}/{b[ds][1]} = {pct(b[ds][0] / b[ds][1])} |")
    cl = chk["closed_loop"]
    out += ["", "Phase 7's rule on the same FD001/FD003 test engines: 11.6% of runs with a drifted sensor.", "",
            "## Closed loop: when the model's own decisions hide the labels", "",
            "In shadow mode every engine eventually fails and gets a label. When the recommended services are carried out "
            "(`--closed-loop`, FD002/FD004 synchronized), a serviced engine never fails, so its label never arrives.", "",
            "| | FD002 | FD004 |", "| --- | --- | --- |",
            f"| Engines whose failure label arrives | {cl['FD002']['failed_labelled']} of {cl['FD002']['engines']} | "
            f"{cl['FD004']['failed_labelled']} of {cl['FD004']['engines']} |",
            f"| Lower-bound miss rate from labels only | {pct(cl['FD002']['miss_rate_from_labels_only'])} | {pct(cl['FD004']['miss_rate_from_labels_only'])} |",
            f"| Bounds using every engine (censored included) | {pct(cl['FD002']['miss_rate_bounds_all_engines'][0])} - "
            f"{pct(cl['FD002']['miss_rate_bounds_all_engines'][1])} | {pct(cl['FD004']['miss_rate_bounds_all_engines'][0])} - "
            f"{pct(cl['FD004']['miss_rate_bounds_all_engines'][1])} |",
            f"| True miss rate (NASA truth; a plant would not know it) | {pct(cl['FD002']['true_miss_rate_same_forecasts'])} | "
            f"{pct(cl['FD004']['true_miss_rate_same_forecasts'])} |", "",
            "The engines that still fail are mostly the model's misses, so a monitor that only learns from failures sees a broken "
            "model where there is none (the FD002 closed-loop replay set the miss-rate flag in "
            f"{flag_rate('fresh_closed_loop')['FD002'][0]} of {flag_rate('fresh_closed_loop')['FD002'][1]} runs). A serviced engine "
            "survived until its service, which rules out a miss when that time already exceeds the forecast's lower bound; the "
            "resulting bounds contain the truth but are too wide to act on, because most services come before the lower bound "
            "has elapsed. A real deployment needs another label source: inspection findings recorded at service, or a small "
            "control group kept on a fixed service policy.", "",
            "## Limitations", "",
            "- C1 failed on FD004 with the pre-registered rule, and the post-hoc fix does not change that; the cause is likely the "
            "fault-mode mixture, not proven.",
            "- All four NASA datasets are now used; no unseen data is left to confirm a further change.",
            "- Calibration fleets have 60 engines (test fleets 100-260); late-replay windows with 15-45 engines are where the "
            "false alarms concentrate.",
            "- Fleet-wide faults only: one engine's broken sensor is a per-engine check, not a fleet drift test.",
            "- The plant clock, services and labels are simulated from NASA's data.", "",
            "## Reproduce", "",
            "Each scenario is one command, e.g. `python -m pipeline.flow --replay-all --monitor v2 --fleet staggered --datasets "
            "FD002 FD004 --schema ops7b_fresh_staggered --out-dir results/phase7b/fresh_staggered` (`--monitor v2.1` for the post-hoc "
            "fix, `--closed-loop` for the closed loop). Health, drift, alert and run tables of every scenario are committed; of the "
            "forecast tables (about 15 MB each) only the three the verifier reads are committed, gzip-compressed. Then "
            "`python -m pipeline.check_phase7b` (with `--closed-loop` and `--diagnosis`), `python -m pipeline.fault_suite FD002 FD004` "
            "(and `--equivalence`), `python -m pipeline.report_phase7b`, `python -m pipeline.verify_phase7b`.", ""]
    return "\n".join(out)


def main() -> int:
    DOC.write_text(render(), encoding="utf-8")
    print(f"Wrote {DOC}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
