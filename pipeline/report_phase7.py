"""Write docs/MONITORING.md from the saved Phase 7 results, so it can never drift from them.

Run:  python -m pipeline.report_phase7       (after the replay and python -m pipeline.check_phase7)
`python -m pipeline.verify_phase7` checks that the committed document equals a fresh rendering.
"""
import json
import sys
from pathlib import Path

from pipeline import config as C
from pipeline import monitoring as M

DOC = Path("docs/MONITORING.md")


def pct(x, d=1):
    return f"{x:.{d}%}"


def render() -> str:
    rule = json.loads(M.RULE_FILE.read_text())
    chk = json.loads(Path("pipeline/phase7_checks.json").read_text())
    res = json.loads(Path("pipeline/results_phase7.json").read_text())
    d, h = rule["drift"], rule["health"]
    fc = chk["flow_check"]
    out = ["# Orchestration and monitoring (Phase 7)", "",
           "Generated by `python -m pipeline.report_phase7` from `pipeline/results_phase7.json`, `pipeline/phase7_checks.json` "
           "and `pipeline/monitoring_rule.json`; do not edit by hand. Independent checks: `python -m pipeline.verify_phase7`. "
           "Walkthrough: `notebooks/07_monitoring.ipynb`.", "",
           "> **What is real and what is simulated.** Forecasts are real outputs of the published LSTM. The plant clock is "
           "simulated: every NASA test engine starts at cycle 1 on shift 1, one shift is one 8-hour cycle, and an engine's "
           "failure enters the plant's log at its true failure cycle (last NASA reading + NASA's true remaining life). Work "
           "orders are recommendations (shadow mode): the recorded NASA data keeps flowing after them.", "",
           "## The shift flow", "",
           f"One Prefect flow run per shift (`pipeline/flow.py`), for each of {', '.join(C.FLOW_DATASETS)}: ingest -> validate -> "
           "load -> features -> predict_and_store -> alerts -> schedule -> model health -> drift -> retraining flag. Steps that touch "
           f"the database or files retry {C.TASK_RETRIES} times, {C.TASK_RETRY_DELAY_SECONDS} s apart. Run IDs are fixed per shift "
           "(`FD001-test-s0137`), so re-running a shift replaces its rows, and a failed shift is resumed by the next run. "
           f"The replay uses its own Postgres schema (`{C.FLOW_SCHEMA}`).", "",
           "- **Model:** the published seed-0 LSTM with rule-E intervals. Before predicting, the flow proves the model reproduces "
           "the published last-cycle predictions and all 100 MC-dropout passes exactly (`maintenance.forecasts.published_model`). "
           "Predictions run in fixed batches of 100 windows, which makes them bit-identical to the published ones.",
           "- **Decisions:** Phase 6's alert rule and CP-SAT planning step (`maintenance.simulate.plan_day`), at the start of each "
           "day (every 2 shifts). The database allows one flow work order per engine.",
           "- **Commands:** `prefect server start` (dashboard http://127.0.0.1:4200), `prefect config set "
           "PREFECT_API_URL=http://127.0.0.1:4200/api`, then `python -m pipeline.flow --once`, `--serve` (a shift every "
           f"{C.SERVE_INTERVAL_SECONDS} s; `--interval` overrides), `--replay-all`, `--reset` (the replay schema only).", "",
           "## Rules fixed before the test replay (validation engines only)", "",
           "`pipeline/calibrate_monitoring.py` chose these on the 20 validation and 80 training engines of each dataset and "
           "committed `pipeline/monitoring_rule.json` before the flow replayed any test data.", "",
           "| Rule | Choice | Evidence on validation |", "| --- | --- | --- |",
           f"| Drift test | per-engine means of the last {d['window_shifts']} shifts vs age-matched training engines, KS, Holm over 14 sensors; "
           f"at least {d['min_engines']} engines a side | reading-level KS rejected: {d['rejected_method'].split(': ', 1)[1]} |",
           f"| Significance | alpha {d['alpha']:g} | false alarms per clean run: " + ", ".join(
               f"{a}: {pct(v)}" for a, v in d["false_alarm_by_alpha"].items()) +
           f"; chosen {pct(d['false_alarm_chosen'], 2)} over {d['runs']} runs (budget {pct(rule['budgets']['drift'], 0)}) |",
           f"| RMSE rule | rolling RMSE of the last {h['window_engines']} labelled engines > {h['rmse_multiplier']:.2f} x validation RMSE "
           f"({', '.join(f'{k} {v['reference_rmse']:.2f}' for k, v in h['reference'].items())}) | 1.30 x would raise false alarms in "
           + ", ".join(f"{k} {pct(v)}" for k, v in h["false_alarm_rmse_at_1.30"].items()) + " of clean windows; chosen: "
           + ", ".join(f"{k} {pct(v)}" for k, v in h["false_alarm_rmse_chosen"].items()) + " |",
           f"| Miss-rate rule | lower-bound miss rate of the last {h['window_engines']} labelled engines > {h['miss_rate_limit']:.0%} | "
           "leave-one-engine-out miss rate " + ", ".join(f"{k} {pct(v['loeo_miss_rate_testlike'])}" for k, v in h["reference"].items())
           + "; false alarms " + ", ".join(f"{k} {pct(v)}" for k, v in h["false_alarm_miss_chosen"].items()) + " |",
           f"| Retraining flag | any of: >= {d['min_drifted_sensors']} drifted sensor, the RMSE rule, the miss-rate rule (health rules "
           f"need {h['min_labelled_engines']} labelled engines) | combined false-alarm estimate {pct(rule['combined_false_alarm_upper_estimate'], 2)} per run |",
           "", "## Can the drift test see a shift?", "",
           "Detection rate when one sensor is shifted, averaged over sensors (weakest sensor in brackets). Validation streams have "
           "20 engines; test windows about 100. *Persistent* = the whole window is shifted; *newest shift* = only the latest readings.", "",
           "| Shift | Validation, persistent | Validation, newest shift | Test windows, newest shift |", "| --- | --- | --- | --- |"]
    tp = chk["test_window_power"]
    for lab in ("+1%", "+2%", "+5%", "+0.5 sd", "+1 sd"):
        vp, vn, t = d["power"].get(f"persistent: {lab}"), d["power"].get(f"newest shift: {lab}"), tp.get(f"newest shift: {lab}")
        cell = lambda v: f"{pct(v['mean'], 0)} ({v['weakest_sensor']} {pct(v['min'], 0)})" if v else "-"
        out.append(f"| {lab} | {cell(vp)} | {cell(vn)} | {cell(t)} |")
    out += ["", "Percent shifts are large for these sensors (+1% is many standard deviations), so most of them also leave the "
                "sensor's allowed range and are quarantined by the validator. Drift is tested on everything received, so it still "
                "sees them; shifts of a fraction of a standard deviation pass validation and are the harder case.", "",
            "## The guide's checks", "",
            "| Step | Check | Result |", "| --- | --- | --- |",
            "| 7.2 | Dashboard loads | `prefect server start` verified (health OK, dashboard HTTP 200) |",
            f"| 7.3 | A shift runs with every task green | {res['runs']} runs over {res['shifts']} shifts, all complete; "
            f"{res['forecasts']:,} forecasts, {res['invalid_forecasts']} invalid; retry, resume and re-run proven in tests/test_flow.py |",
            "| 7.4 | Runs appear on their own | `.serve()` created auto-scheduled runs that continued shift by shift |",
            f"| 7.5 | Model health per run | fact_model_health: one row per run, scored only once failures are in the log |",
            f"| 7.6 | Shifted batch flagged, normal batches mostly not | +5% on {fc['sensor']} ({fc['dataset']}): {fc['plus5pct']['quarantined']} of "
            f"{fc['plus5pct']['readings']} readings quarantined, drifted {fc['plus5pct']['drifted']}; clean test runs with a drifted "
            f"sensor: {pct(res['drift_false_alarm_rate_test'], 2)} |",
            f"| 7.7 | The shifted batch sets the flag | needs_retraining = {fc['plus5pct']['needs_retraining']}; the {fc['clean_runs']} clean "
            f"runs before it: {fc['clean_runs_flagged']} flagged |", "",
            f"An in-range shift (+1 sd on {fc['sensor']} in one shift): {fc['plus1sd']['quarantined']} quarantined, drifted "
            f"{fc['plus1sd']['drifted'] or 'none'}, flag {fc['plus1sd']['needs_retraining']}.", "",
            "## Did the pre-registered rule hold up on clean test data?", ""]
    rp, dd, hd = chk["replay"], chk["drift_diagnosis"], chk["health_diagnosis"]
    flag_rate = rp["runs_flagged_for_retraining"] / rp["runs"]
    out += ["| Target | Validation (when chosen) | Clean test replay | Met? |", "| --- | --- | --- | --- |",
            f"| Drift false alarms <= 5% of runs | {pct(d['false_alarm_chosen'], 2)} | {pct(rp['drift_false_alarm_rate'], 1)} "
            f"({rp['runs_with_a_drifted_sensor']} of {rp['runs_with_drift_test']} tested runs; "
            + ", ".join(f"{k} {pct(v, 1)}" for k, v in rp["by_dataset"].items()) + f") | {'yes' if rp['drift_false_alarm_rate'] <= 0.05 else '**no**'} |",
            f"| Retraining flag on clean data <= 5% of runs | estimate {pct(rule['combined_false_alarm_upper_estimate'], 1)} | "
            f"{pct(flag_rate, 1)} ({rp['runs_flagged_for_retraining']} of {rp['runs']} runs) | {'yes' if flag_rate <= 0.05 else '**no**'} |", "",
            "Nothing was injected in the replay, so every flag above is a false alarm. The limits were not moved after seeing "
            "them (that would tune the rule on the test engines). Both causes were traced:", "",
            "**1. The drift reference matches age, not wear.** NASA cut each test engine off at a different point, so late in the "
            "replay the engines still reporting are a selected group that is healthier than the training engines of the same "
            "age (which run to failure). In the flagged windows:", "",
            "| Dataset | Runs | Median remaining life: test engines | Median remaining life: reference | Within 50 cycles of failure: test | Within 50: reference |",
            "| --- | --- | --- | --- | --- | --- |"]
    for ds, v in dd["by_dataset"].items():
        for kind, lab in (("drift_runs", "flagged"), ("clean_runs", "not flagged")):
            if kind in v:
                x = v[kind]
                out.append(f"| {ds} | {x['runs']} {lab} | {x['median_rul_test']:.0f} | {x['median_rul_reference']:.0f} | "
                           f"{pct(x['share_near_failure_test'], 0)} | {pct(x['share_near_failure_reference'], 0)} |")
    out += ["", f"Every sensor that 'drifted' ({', '.join(f'{s} {n}x' for s, n in dd['drift_count_by_sensor'].items())}) is among the "
                f"{dd['top_wear_n']} sensors most correlated with remaining life ({', '.join(dd['sensors_by_wear'][:dd['top_wear_n']])}); "
                "the least wear-related sensors never drifted. The test detected a difference in wear, not a sensor fault. Validation "
                "engines run to failure without this cut-off, which is why the calibration did not see it.", "",
            "**2. The first labels come from the shortest-lived engines.** Labels arrive in order of failure, so the first window "
            "of 20 holds the engines that failed first, and the model is less accurate on them:", "",
            "| Dataset | First 20 labelled: median life, RMSE | Other 80: median life, RMSE |", "| --- | --- | --- |"]
    for ds, v in hd.items():
        out.append(f"| {ds} | {v['first_window']['median_life']:.0f} cycles, {v['first_window']['rmse']:.2f} | "
                   f"{v['other_engines']['median_life']:.0f} cycles, {v['other_engines']['rmse']:.2f} |")
    out += ["", "**What would fix it** (not done here, because it would need data not yet seen to confirm): a drift reference "
                "matched on wear stage as well as age, and an RMSE reference that matches the life of the engines labelled so far, "
                "both chosen on validation engines cut off the way NASA cut the test engines, then confirmed on a fresh dataset "
                "(FD002 or FD004), the way Phase 5b confirmed the model on FD003.", "",
            "## Model health over the replay", "",
            "| Dataset | First label (shift) | All 100 labelled (shift) | Rule active from (shift) | Final RMSE (all 100) | Final coverage | "
            "Final lower-bound miss rate | Rolling RMSE while active | Highest rolling miss rate | Runs flagged |",
            "| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |"]
    for ds, r in res["datasets"].items():
        f, w = r["final_cum"], r["rolling_while_active"]
        out.append(f"| {ds} | {r['first_label_shift']} | {r['all_labelled_shift']} | {r['rule_active_from_shift']} | {f['rmse']:.2f} | "
                   f"{pct(f['coverage_90'], 0)} | {pct(f['lower_bound_miss_rate'], 0)} | {w['rmse_min']:.2f}-{w['rmse_max']:.2f} | "
                   f"{pct(w['miss_rate_max'], 0)} | {r['flagged_runs']} of {r['runs']} |")
    out += ["", "The final RMSE over all 100 engines equals the published test RMSE (the same last-cycle predictions), which ties "
                "the monitoring numbers to Phases 5 and 5b."]
    for ds, r in res["datasets"].items():
        if r["flagged_runs"]:
            out.append("")
            out.append(f"**{ds} retraining flags:** {r['flagged_runs']} runs, reasons " +
                       ", ".join(f"{k} ({v})" for k, v in r["flag_reasons"].items()) +
                       f"; shifts {r['flagged_shifts'][0]}-{r['flagged_shifts'][-1]}." +
                       (" These are the health rules reacting to the labelled engines, not drift." if not any(
                           k.startswith("drift") for k in r["flag_reasons"]) else ""))
    out += ["", "## Limitations", "",
            "- One shift is one cycle and all engines start together; a real fleet is staggered.",
            "- Labels come late: an engine is scored only after it fails, so the health rules see nothing until the first "
            "failures and only ever see the engines that fail first early on.",
            "- In shadow mode recommended services do not stop the data. If they were executed, most engines would be serviced "
            "before failing and their labels would never arrive (censoring), which a real deployment has to plan for.",
            "- Validation streams have 20 engines, so the false-alarm and power estimates are coarse; test windows have ~100.",
            "- The exact model check runs only on the operating system that published the model; CI on Linux replays the "
            "committed predictions instead.", ""]
    return "\n".join(out)


def main() -> int:
    DOC.write_text(render(), encoding="utf-8")
    print(f"Wrote {DOC}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
