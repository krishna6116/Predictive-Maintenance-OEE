"""Write docs/MODEL_METRICS_PHASE5B.md from the saved Phase 5b results, so it can never drift from them.

Run:  python -m models.report_phase5b       (after python -m models.run_fd003)
`python -m models.verify_fd003` checks that the committed document equals a fresh rendering.
"""
import json
import sys
from pathlib import Path

DOC = Path("docs/MODEL_METRICS_PHASE5B.md")
XGB = "XGBoost, all 168 features"
OS_NAMES = {"win32": "Windows", "linux": "Linux", "darwin": "macOS"}


def ci(c, digits=2):
    return f"{c[0]:+.{digits}f} to {c[1]:+.{digits}f}"


def render() -> str:
    r = json.loads(Path("models/results_phase5b.json").read_text())
    rule = json.loads(Path("models/calibration_rule.json").read_text())
    p5 = json.loads(Path("models/results_phase5.json").read_text())
    M, mc, env, T, v = r["models"], r["mc_dropout"], r["environment"], r["tests"], r["verdict"]
    f3, f1 = mc["FD003"], mc["FD001_post_hoc"]
    out = ["# Model metrics: Phase 5b (FD003 confirmation and interval calibration)", "",
           "Generated by `python -m models.report_phase5b` from `models/results_phase5b.json`; do not edit by hand. "
           "Independent checks: `python -m models.verify_fd003`. FD001 results: `docs/MODEL_METRICS.md`, `docs/MODEL_METRICS_PHASE5.md`.", "",
           "## Why this phase", "",
           "Phase 5 left three weak spots: 100 FD001 test engines could not separate the LSTM from XGBoost; everything was "
           "tested on one fault mode; and the 90% intervals covered only 82% of test engines. FD001's test set had already been "
           "seen, so fixing anything and re-scoring it there would be tuning to the test set. This phase uses NASA's **FD003** "
           "(100 new test engines, a second fault mode) as a fresh confirmation set, with every choice fixed in advance.", "",
           "## Fixed before FD003 was used (two dated commits)", "",
           f"1. **Interval rule** (`models/calibration_rule.json`, chosen on FD001 validation only). Candidates, leave-engines-out "
           "coverage of the nominal 90% interval:", "",
           "| Rule | Test-like readings | Near failure (true RUL <= 50) | Mean width, test-like (cycles) |", "| --- | --- | --- | --- |"]
    for name, c in rule["candidates"].items():
        mark = " **(chosen)**" if name == rule["chosen"] else ""
        out.append(f"| {name}: {c['rule']}{mark} | {c['loeo_coverage_testlike']:.1%} | {c['loeo_coverage_near_failure']:.1%} | {c['mean_width_testlike']:.1f} |")
    s = r["frozen_from_fd001"]["deep_settings"]
    out += ["", "2. **Frozen recipe** (`models/run_fd003.py`): the 14 sensors, 168 features, RUL cap 125, XGBoost depth "
            f"{r['frozen_from_fd001']['xgb_depth']}, LSTM (window {s['LSTM']['window']}, hidden {s['LSTM']['hidden']}, dropout "
            f"{s['LSTM']['dropout']}, learning rate {s['LSTM']['lr']:g}) and CNN (window {s['CNN']['window']}, hidden {s['CNN']['hidden']}, "
            f"dropout {s['CNN']['dropout']}, learning rate {s['CNN']['lr']:g}). Learned on FD003's own {r['split']['val']} validation "
            "engines by the same procedures: scaler (training engines only), tree and epoch counts (early stopping), Ridge penalty, "
            "interval scale factors.",
            "3. **Pre-registered tests H1-H8** in one Holm family, and the verdict rule.", "",
            f"**Environment:** {OS_NAMES.get(env['os'], env['os'])}, Python {env['python']}, PyTorch {env['torch']}, XGBoost "
            f"{env['xgboost']}, {env['threads']} CPU thread. Run time {r['seconds_total'] / 60:.0f} minutes.", "",
            "## FD003 results (100 test engines, scored once)", "",
            "| Model | Validation RMSE (all / test-like) | Test RMSE (95% interval) | MAE | PHM08 | Near-failure MAE | Late | 5 seeds: test RMSE mean +/- sd |",
            "| --- | --- | --- | --- | --- | --- | --- | --- |"]
    for name, m in M.items():
        seeds = f"{m['seed_test_rmse_mean']:.2f} +/- {m['seed_test_rmse_std']:.2f}" if "seed_test_rmse" in m else "-"
        out.append(f"| {name} | {m['val_rmse']:.2f} / {m['val_rmse_testlike']:.2f} | {m['rmse']:.2f} ({m['rmse_ci95'][0]:.1f} to "
                   f"{m['rmse_ci95'][1]:.1f}) | {m['mae']:.2f} | {m['phm']:,.0f} | {m['near_failure_mae']:.1f} | {m['late_share']:.0%} | {seeds} |")
    out += ["", "Near-failure MAE: test engines with true RUL <= 50. Epochs per seed: " +
            "; ".join(f"{a} {M[a]['epochs_per_seed']}" for a in ("LSTM", "CNN")) + f"; XGBoost trees per seed {M[XGB]['settings']['trees_per_seed']}.", "",
            "## Both datasets together (200 test engines)", "",
            "| Model | Pooled RMSE | Pooled near-failure MAE | FD001 RMSE | FD003 RMSE |", "| --- | --- | --- | --- | --- |"]
    fd1 = {"LSTM": p5["models"]["LSTM"]["rmse"], "CNN": p5["models"]["CNN"]["rmse"], XGB: p5["baseline"]["rmse"]}
    for name, pz in r["pooled_fd001_fd003"].items():
        out.append(f"| {name} | {pz['rmse']:.2f} | {pz['near_failure_mae']:.2f} | {fd1[name]:.2f} | {M[name]['rmse']:.2f} |")
    out += ["", "## Pre-registered tests (paired bootstrap; Holm over all 8)", "",
            "| Test | Gap A - B (95% interval) | p | Holm p |", "| --- | --- | --- | --- |"]
    for k, t in T.items():
        gap = f"{t['diff']:+,.0f}" if "PHM08" in k else f"{t['diff']:+.2f} ({ci(t['ci'])})"
        out.append(f"| {k} | {gap} | {t['p']:.3f} | {t['p_holm']:.3f}{' (significant)' if t['significant'] else ''} |")
    h1 = next(t for k, t in T.items() if k.startswith("H1 "))
    pz = r["pooled_fd001_fd003"]
    out += ["", "## Verdict", "", f"Rule: {v['rule']}.", "",
            (f"**The LSTM replaces XGBoost as the published model.** Pooled over 200 engines its RMSE gap is {h1['diff']:+.2f} "
             f"(95% interval {ci(h1['ci'])}, Holm p {h1['p_holm']:.3f}) and its near-failure MAE is {pz['LSTM']['near_failure_mae']:.2f} vs "
             f"{pz[XGB]['near_failure_mae']:.2f} cycles."
             if v["deep_wins"] else
             f"**XGBoost remains the published model.** Pooled over 200 engines the LSTM's RMSE gap is {h1['diff']:+.2f} "
             f"(95% interval {ci(h1['ci'])}, Holm p {h1['p_holm']:.3f}), "
             + ("significant" if h1["significant"] else "not significant")
             + f"; pooled near-failure MAE {pz['LSTM']['near_failure_mae']:.2f} (LSTM) vs {pz[XGB]['near_failure_mae']:.2f} (XGBoost) cycles."),
            "", "## Interval calibration (LSTM seed 0, MC dropout)", "",
            f"Rule E learns two scale factors on the dataset's validation engines (FD003: k = {f3['k_near']:.2f} when predicted RUL <= "
            f"{rule['near_zone_cycles']}, {f3['k_far']:.2f} otherwise).", "",
            "| Coverage of the nominal 90% interval | All test engines | Near failure | Mean width (cycles) |", "| --- | --- | --- | --- |",
            f"| FD003, raw MC percentiles | {f3['raw_test_coverage']:.0%} | - | - |",
            f"| FD003, Phase 5 rule (one k = {f3['phase5_rule_k']:.2f}) | {f3['phase5_rule_test_coverage']:.0%} | {f3['phase5_rule_test_coverage_near_failure']:.0%} | - |",
            f"| **FD003, rule E (pre-registered)** | **{f3['test_coverage']:.0%}** | **{f3['test_coverage_near_failure']:.0%}** | {f3['test_mean_width']:.1f} |",
            f"| FD001, rule E (post hoc: FD001 test was already seen) | {f1['test_coverage']:.0%} | {f1['test_coverage_near_failure']:.0%} | {f1['test_mean_width']:.1f} |", "",
            "## Reproducibility", "",
            "- Same OS and library versions: `python -m models.verify_fd003` re-trains LSTM and XGBoost seed 0 and requires identical "
            "test predictions. Other OS (CI runs Linux): one re-trained seed must land within 4 seed standard deviations of the "
            "published 5-seed mean, backed by the exact checks (scaler and every window rebuilt independently).", ""]
    return "\n".join(out)


def main() -> int:
    DOC.write_text(render(), encoding="utf-8")
    print(f"Wrote {DOC}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
