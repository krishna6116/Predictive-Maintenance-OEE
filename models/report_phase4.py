"""Write docs/MODEL_METRICS.md from the saved Phase 4 results, so the document can never drift from them.

Run:  python -m models.report_phase4        (after python -m models.baselines)
`python -m models.verify_baselines` checks that the committed document equals a fresh rendering.
"""
import json
import sys
from pathlib import Path

import pandas as pd

from models.metrics import mae, paired_bootstrap

RESULTS = Path("models/results_phase4.json")
DOC = Path("docs/MODEL_METRICS.md")
MAIN = "XGBoost, all 168 features"
RIDGE = "Ridge, all 168 features"


def fmt_ci(ci, digits=1, signed=False):
    f = f"{{:+.{digits}f}}" if signed else f"{{:.{digits}f}}"
    return f"{f.format(ci[0])} to {f.format(ci[1])}"


def render() -> str:
    r = json.loads(RESULTS.read_text())
    preds = pd.read_csv("models/predictions_phase4.csv")
    m = r["models"]
    out = ["# Model metrics", "",
           "Generated by `python -m models.report_phase4` from `models/results_phase4.json`; do not edit by hand. "
           "Independent checks: `python -m models.verify_baselines`. Walkthrough: `notebooks/04_baselines.ipynb`.", "",
           "**Data:** NASA C-MAPSS FD001, 100 official test engines, each scored at its last observed cycle. "
           "**Protocol:** " + r["protocol"] + ". Scores against NASA's uncapped values are in the results file. "
           "Intervals are 95% bootstrap intervals over test engines (2,000 resamples).", "",
           "## Phase 4: baselines", "",
           "| Model | Inputs | Validation RMSE (all rows / test-like) | Test RMSE (95% interval) | MAE | PHM08 | Late predictions |",
           "| --- | --- | --- | --- | --- | --- | --- |"]
    for name, v in m.items():
        label = f"**{name} (published baseline)**" if name == MAIN else name
        out.append(f"| {label} | {v['features']} | {v['val_rmse']:.2f} / {v['val_rmse_testlike']:.2f} | "
                   f"{v['rmse']:.2f} ({fmt_ci(v['rmse_ci95'])}) | {v['mae']:.2f} | {v['phm']:,.0f} | {v['late_share']:.0%} |")
    x = m[MAIN]
    ridge_curve = m["Ridge, raw sensors (14)"]["settings"]["val_rmse_by_alpha"]
    out += ["",
            f"- **Test-like validation** uses {r['test_like_validation']}, matching the test set's observed lengths "
            "and RUL range. It is closer to the test score than the all-rows validation score, which includes many "
            "easy readings at the 125 cap.",
            f"- **XGBoost depth** (searched 3, 5, 7 with seed 0): all-rows validation RMSE "
            + ", ".join(f"{float(v):.2f}" for v in r["xgb_depth_search_val_rmse"].values()) + "; test-like "
            + ", ".join(f"{float(v):.2f}" for v in r["xgb_depth_search_val_rmse_testlike"].values())
            + f". Both pick depth {x['settings']['max_depth']}.",
            f"- **Seed stability:** across 5 seeds the main model's test RMSE is {x['seed_test_rmse_mean']:.2f} "
            f"+/- {x['seed_test_rmse_std']:.2f}; seed 0 is published.",
            "- **Ridge penalty barely matters:** validation RMSE on raw sensors is "
            + ", ".join(f"{float(v):.2f}" for v in ridge_curve.values()) + " for alpha "
            + ", ".join(ridge_curve) + ".", "",
            "## How the published model was chosen (validation only)", "",
            "Whole engines are resampled, because each validation engine contributes many rows.", "",
            "| Comparison on the 20 validation engines | Gap A - B (95% interval) |", "| --- | --- |"]
    for name, sel in r["model_selection_on_validation"].items():
        nf, tl = sel["val_near_failure_mae"], sel["val_testlike_rmse"]
        out.append(f"| {name}: MAE, readings with <= 50 cycles left | {nf['diff']:+.2f} ({fmt_ci(nf['ci'], 2, True)}) |")
        out.append(f"| {name}: RMSE, test-like readings | {tl['diff']:+.2f} ({fmt_ci(tl['ci'], 2, True)}) |")
    out += ["", "XGBoost is chosen because it is clearly better than Ridge near failure and on test-like rows, on "
            "validation data. The test set only confirms this choice (next sections).", "",
            "## Which test-set differences are real (paired bootstrap, Holm-corrected)", "",
            "| A vs B | RMSE gap A - B (95% interval) | Holm p | PHM08 gap | Holm p | Verdict |",
            "| --- | --- | --- | --- | --- | --- |"]
    for name, c in r["paired_comparisons"].items():
        a, b = c["rmse"], c["phm"]
        verdict = ("A better on both" if a["significant"] and b["significant"] and a["diff"] < 0 and b["diff"] < 0 else
                   "A better on RMSE" if a["significant"] and a["diff"] < 0 else
                   "A better on PHM08" if b["significant"] and b["diff"] < 0 else "no clear difference")
        out.append(f"| {name} | {a['diff']:+.2f} ({fmt_ci(a['ci'], 2, True)}) | {a['p_holm']:.3f} | "
                   f"{b['diff']:+,.0f} | {b['p_holm']:.3f} | {verdict} |")
    near = preds.RUL <= 50
    rows = []
    for name in (MAIN, RIDGE):
        d = preds[name][near] - preds.RUL[near]
        rows.append(f"| {name} | {d.abs().mean():.1f} | {d.mean():+.1f} | {(d > 0).mean():.0%} |")
    robust = []
    for t in (25, 40, 50, 60, 75, 100):
        n = preds.RUL <= t
        c = paired_bootstrap(preds.RUL[n], preds[MAIN][n], preds[RIDGE][n], metric=mae)
        robust.append(f"| <= {t} | {int(n.sum())} | {c['diff']:+.1f} ({fmt_ci(c['ci'], 1, True)}) |")
    err = (preds[MAIN] - preds.RUL).abs()
    bands = pd.cut(preds.RUL, [0, 25, 50, 75, 100, 125], include_lowest=True)
    band_mae = err.groupby(bands, observed=False).mean()
    out += ["", "## Test confirmation near failure", "",
            f"| Test engines with <= 50 cycles left ({int(near.sum())}) | MAE | Mean signed error (+ = late) | Late share |",
            "| --- | --- | --- | --- |", *rows, "",
            "The same comparison at other cut-offs (MAE gap XGBoost - Ridge):", "",
            "| Cycles left | Engines | Gap (95% interval) |", "| --- | --- | --- |", *robust, "",
            "XGBoost's MAE by true RUL band (cycles): "
            + ", ".join(f"{int(iv.left) if iv.left > 0 else 0}-{int(iv.right)}: {v:.1f}" for iv, v in band_mae.items()) + ".",
            "", "## Conclusions", "",
            f"1. Feature engineering is the largest real gain: the same Ridge model goes from "
            f"{m['Ridge, raw sensors (14)']['rmse']:.2f} to {m[RIDGE]['rmse']:.2f} RMSE.",
            f"2. Age alone ({m['Age only (cycle count)']['rmse']:.2f}) beats the fleet average "
            f"({m['Fleet average']['rmse']:.2f}) but is far behind any sensor model.",
            "3. Over all test engines, XGBoost and Ridge on the same features are statistically tied; near failure, "
            "XGBoost is clearly better on validation and on test, so it is the published baseline.",
            "4. Removing FFT, EMA, or s9 and s14 has no measurable effect; the features are kept and this is stated.",
            f"5. **Bar for Phase 5:** beat {x['rmse']:.2f} RMSE and {x['phm']:,.0f} PHM08 with a paired, "
            "Holm-corrected interval that excludes 0, and stay at least as accurate near failure.", ""]
    return "\n".join(out)


def main() -> int:
    DOC.write_text(render(), encoding="utf-8")
    print(f"Wrote {DOC}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
