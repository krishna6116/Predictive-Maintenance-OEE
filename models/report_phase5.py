"""Write docs/MODEL_METRICS_PHASE5.md from the saved Phase 5 results, so it can never drift from them.

Run:  python -m models.report_phase5        (after python -m models.run_deep)
A separate document (not an extension of docs/MODEL_METRICS.md) keeps Phase 4's verified document and verifier
unchanged; Phase 4 numbers used here are read from models/results_phase4.json, never retyped.
`python -m models.verify_deep` checks that the committed document equals a fresh rendering.
"""
import json
import math
import sys
from pathlib import Path

import numpy as np

DOC = Path("docs/MODEL_METRICS_PHASE5.md")
XGB = "XGBoost, all 168 features"
RIDGE = "Ridge, all 168 features"
OS_NAMES = {"win32": "Windows", "linux": "Linux", "darwin": "macOS"}


def ci(c, digits=2, signed=True):
    f = f"{{:+.{digits}f}}" if signed else f"{{:.{digits}f}}"
    return f"{f.format(c[0])} to {f.format(c[1])}"


def render() -> str:
    r = json.loads(Path("models/results_phase5.json").read_text())
    p4 = json.loads(Path("models/results_phase4.json").read_text())["models"]
    M, mc, env, pub = r["models"], r["mc_dropout"], r["environment"], r["published_deep_model"]
    abl = next(n for n in M if "168-feature" in n)
    out = ["# Model metrics: Phase 5 (deep learning)", "",
           "Generated by `python -m models.report_phase5` from `models/results_phase5.json`; do not edit by hand. "
           "Independent checks: `python -m models.verify_deep`. Walkthrough: `notebooks/05_deep.ipynb`. "
           "Phase 4 baselines: `docs/MODEL_METRICS.md`.", "",
           "**Data:** NASA C-MAPSS FD001, the same 100 test engines as Phase 4, each scored once at its last observed cycle. "
           "**Protocol:** " + r["protocol"] + ".", "",
           f"**Environment:** {OS_NAMES.get(env['os'], env['os'])}, Python {env['python']}, PyTorch {env['torch']}, "
           f"{env['threads']} CPU thread, deterministic algorithms on. Total run time {r['seconds_total'] / 60:.0f} minutes.", "",
           "## Inputs and training", "",
           f"- **Windows:** the last W cycles of the 14 scaled sensors, ending at the current cycle; "
           f"{r['search_space']['padding']} when fewer than W readings exist.",
           f"- **Training:** {r['search_space']['optimizer']}, {r['search_space']['loss']}, batch {r['search_space']['batch']}, "
           f"up to {r['search_space']['max_epochs']} epochs with early stopping (patience {r['search_space']['patience']}) on "
           "the validation RMSE; the refit on all 100 training engines uses each seed's validated epoch count.", "",
           "## Search (seed 0, validation only)", "",
           "| Stage | Model | Window | Hidden | Dropout | Learning rate | Validation RMSE (all / test-like) | Best epoch | Seconds |",
           "| --- | --- | --- | --- | --- | --- | --- | --- | --- |"]
    for s in r["search"]:
        out.append(f"| {s['stage']} | {s['arch']} | {s['window']} | {s['hidden']} | {s['dropout']} | {s['lr']:g} | "
                   f"{s['val_rmse']:.2f} / {s['val_rmse_testlike']:.2f} | {s['best_epoch']} | {s['seconds']:.0f} |")
    out += ["", "Final settings: " + "; ".join(
        f"**{a}** window {c['window']}, hidden {c['hidden']}, dropout {c['dropout']}, learning rate {c['lr']:g}"
        for a, c in r["final_settings"].items()) + ".", "",
            f"5-seed validation RMSE: " + ", ".join(f"{a} {v:.2f}" for a, v in r["val_rmse_5seed_mean"].items())
            + f". The published deep model is **{pub}** (lower 5-seed validation RMSE).", "",
            "## Results on the 100 test engines", "",
            "| Model | Validation RMSE (all / test-like) | Test RMSE (95% interval) | MAE | PHM08 | Near-failure MAE | Late | 5 seeds: test RMSE mean +/- sd | Training time per seed |",
            "| --- | --- | --- | --- | --- | --- | --- | --- | --- |"]
    for name, m in M.items():
        t = (np.mean(m["seconds_val_runs"]) + np.mean(m["seconds_refits"])) / 60
        label = f"**{name} (published deep model)**" if name == pub else name
        out.append(f"| {label} | {m['val_rmse']:.2f} / {m['val_rmse_testlike']:.2f} | {m['rmse']:.2f} ({ci(m['rmse_ci95'], 1, False)}) | "
                   f"{m['mae']:.2f} | {m['phm']:,.0f} | {m['near_failure_mae']:.1f} | {m['late_share']:.0%} | "
                   f"{m['seed_test_rmse_mean']:.2f} +/- {m['seed_test_rmse_std']:.2f} | {t:.1f} min |")
    b = r["baseline"]
    x4 = p4[XGB]
    out.append(f"| {XGB} (Phase 4 baseline) | {x4['val_rmse']:.2f} / {x4['val_rmse_testlike']:.2f} | {x4['rmse']:.2f} "
               f"({ci(x4['rmse_ci95'], 1, False)}) | {x4['mae']:.2f} | {x4['phm']:,.0f} | {b['near_failure_mae']:.1f} | "
               f"{x4['late_share']:.0%} | {x4['seed_test_rmse_mean']:.2f} +/- {x4['seed_test_rmse_std']:.2f} | - |")
    out += ["", "Near-failure MAE: test engines with true RUL <= 50. Scores against NASA's uncapped RUL are in the results file.", "",
            "## Compared with XGBoost on validation (whole engines resampled)", "",
            "| Comparison | Gap A - B (95% interval) |", "| --- | --- |"]
    for name, sel in r["model_selection_on_validation"].items():
        t_, n_ = sel["val_testlike_rmse"], sel["val_near_failure_mae"]
        out.append(f"| {name}: RMSE, test-like readings | {t_['diff']:+.2f} ({ci(t_['ci'])}) |")
        out.append(f"| {name}: MAE, readings with <= 50 cycles left | {n_['diff']:+.2f} ({ci(n_['ci'])}) |")
    out += ["", "## Test-set comparisons (paired bootstrap; Holm over all tests below as one family)", "",
            "| A vs B | RMSE gap (95% interval), Holm p | PHM08 gap, Holm p | Near-failure MAE gap (95% interval), Holm p |",
            "| --- | --- | --- | --- |"]
    for name, c in r["paired_comparisons"].items():
        a, p_, n_ = c["rmse"], c["phm"], c["near_failure_mae"]
        star = lambda v: " (significant)" if v["significant"] else ""
        out.append(f"| {name} | {a['diff']:+.2f} ({ci(a['ci'])}), {a['p_holm']:.3f}{star(a)} | {p_['diff']:+,.0f}, "
                   f"{p_['p_holm']:.3f}{star(p_)} | {n_['diff']:+.2f} ({ci(n_['ci'])}), {n_['p_holm']:.3f}{star(n_)} |")
    v = r["verdict"]
    c = r["paired_comparisons"][f"{pub} vs {XGB}"]
    out += ["", "## Verdict", "", f"Rule: {v['rule']}.", "",
            (f"**The deep model wins.** {pub} beats XGBoost on RMSE after Holm correction (gap {c['rmse']['diff']:+.2f}) and is at "
             f"least as accurate near failure ({M[pub]['near_failure_mae']:.1f} vs {b['near_failure_mae']:.1f} cycles)."
             if v["deep_wins"] else
             f"**XGBoost remains the published model.** {pub}'s RMSE gap vs XGBoost is {c['rmse']['diff']:+.2f} "
             f"(95% interval {ci(c['rmse']['ci'])}, Holm p {c['rmse']['p_holm']:.3f}), "
             + ("not significant" if not c["rmse"]["significant"] else "significant")
             + f", and its near-failure MAE is {M[pub]['near_failure_mae']:.1f} vs XGBoost's {b['near_failure_mae']:.1f} cycles."),
            "", "## MC-dropout uncertainty (published deep model, seed 0)", "",
            f"{mc['passes']} predictions per engine with dropout on. Raw interval: the 5th-95th percentile of the passes "
            f"(nominal {mc['nominal']:.0%}). Calibrated interval: MC mean +/- k x MC sd, with k = {mc['scale_k']:.2f} chosen so "
            f"{mc['nominal']:.0%} of validation truths are covered; k comes from the 80-engine model on validation and is "
            "applied unchanged to the refit model on test.", "",
            "| Coverage of the nominal 90% interval | Raw | Calibrated |", "| --- | --- | --- |",
            f"| Validation, all readings | {mc['raw']['val_coverage']:.1%} | {mc['calibrated']['val_coverage_leave_engines_out']:.1%} (leave-engines-out; in-sample {mc['calibrated']['val_coverage_in_sample']:.1%}) |",
            f"| Validation, test-like readings | {mc['raw']['val_coverage_testlike']:.1%} | {mc['calibrated']['val_coverage_testlike']:.1%} (in-sample k) |",
            f"| Test, 100 engines (scored once) | {mc['raw']['test_coverage']:.1%} | {mc['calibrated']['test_coverage']:.1%} |",
            f"| Test, near failure (true RUL <= 50) | {mc['raw']['test_coverage_near_failure']:.1%} | {mc['calibrated']['test_coverage_near_failure']:.1%} |",
            f"| Mean interval width, test (cycles) | {mc['raw']['test_mean_width']:.1f} | {mc['calibrated']['test_mean_width']:.1f} |", "",
            f"Test RMSE of the MC mean: {mc['mc_mean_test_rmse']:.2f}, vs {mc['point_test_rmse']:.2f} for the dropout-off point prediction "
            "(which is the one scored above).", ""]
    sd, n = M[pub]["seed_test_rmse_std"], len(M[pub]["seed_test_rmse"])
    tol = 4.0 * sd * math.sqrt(1 + 1 / n)
    t = json.loads(Path("models/tolerance_phase5.json").read_text())
    out += ["## Reproducibility", "",
            "- **Same OS and PyTorch version as the published run:** `python -m models.verify_deep` re-trains seed 0 and requires "
            "identical test predictions and identical MC passes (difference exactly 0).",
            f"- **Other OS (CI runs Linux):** floating-point kernels differ, so one re-trained seed's test RMSE must lie within "
            f"4 x {sd:.2f} x sqrt(1 + 1/{n}) = **{tol:.2f}** of the published 5-seed mean ({M[pub]['seed_test_rmse_mean']:.2f}). "
            "With the published seed sd, a correct re-run falls outside this band by chance with probability well under 0.1%.",
            "- **Input bugs are caught exactly, on any OS.** The verifier rebuilds every training and test window from the raw "
            "files with independent plain-Python code and requires a value-by-value match; it also checks that seed 0 is refit "
            "for the epoch count found by the validation search. The band above is loose, so it is only relied on for "
            "broken training.",
            f"- **Every deliberate bug is caught by at least one of these checks.** Measured by `python -m models.tolerance_phase5` "
            f"on the validation engines (the test set is not used): the correct model scores {t['correct_validation_rmse']:.2f}.", "",
            "| Deliberate bug | Validation RMSE | Shift vs correct | Caught by |", "| --- | --- | --- | --- |"]
    for k, v in t["bugs"].items():
        out.append(f"| {k} | {v['validation_rmse']:.2f} | {v['shift_vs_correct']:+.2f} | {', '.join(v['caught_by']) or 'nothing'} |")
    out.append("")
    return "\n".join(out)


def main() -> int:
    DOC.write_text(render(), encoding="utf-8")
    print(f"Wrote {DOC}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
